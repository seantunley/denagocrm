#!/usr/bin/env node
/**
 * Refresh src/lib/modelPrices.generated.ts — the Claude list prices the AI usage meter is costed at — from LiteLLM's
 * public price file (Sean, 2026-11-20, from Scarlet's weekly price job: a hand-kept list priced every new model as
 * Opus, and that meter is billable).
 *
 *   node scripts/update-model-prices.mjs          rewrite the file
 *   node scripts/update-model-prices.mjs --check  exit 1 if it would change (nothing written)
 *
 * Run weekly by .github/workflows/model-prices.yml, which opens a PR when a price changed or a model was added. A
 * price only ever reaches the meter through a reviewed PR.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export const SOURCE = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";
const OUT = new URL("../src/lib/modelPrices.generated.ts", import.meta.url);

const round = (n) => Math.round(n * 1e6) / 1e6;
const perMillion = (perToken) => round(Number(perToken) * 1e6);
const usable = (n) => Number.isFinite(n) && n >= 0;
/** A listed price, or Anthropic's standard multiple of the input price when the file has none. */
const priced = (perToken, fallback) => (perToken != null && usable(perMillion(perToken)) ? perMillion(perToken) : fallback);

/**
 * LiteLLM's file → [model id, input, output, cache write, cache read] in US$ per million tokens, sorted. Anthropic's
 * own API ids only (its Bedrock/Vertex copies have other ids and can differ). A row without both main prices is skipped.
 */
export function pricesFrom(json) {
  const rows = [];
  for (const [id, row] of Object.entries(json ?? {})) {
    if (!row || row.litellm_provider !== "anthropic" || !/^claude-[a-z0-9-]+$/.test(id)) continue;
    const input = perMillion(row.input_cost_per_token);
    const output = perMillion(row.output_cost_per_token);
    if (!usable(input) || !usable(output) || input === 0 || output === 0) continue;
    rows.push([id, input, output, priced(row.cache_creation_input_token_cost, round(input * 1.25)), priced(row.cache_read_input_token_cost, round(input * 0.1))]);
  }
  return rows.sort((a, b) => a[0].localeCompare(b[0]));
}

export function render(rows) {
  const lines = rows.map(([id, ...p]) => `  ${JSON.stringify(id)}: [${p.join(", ")}],`);
  return [
    "// GENERATED by scripts/update-model-prices.mjs from LiteLLM's public price file — do not edit by hand.",
    "// Refreshed weekly by .github/workflows/model-prices.yml (a PR, reviewed before it reaches the meter).",
    "",
    "/** US$ per million tokens: [input, output, cache write, cache read]. */",
    "export const GENERATED_MODEL_PRICES: Readonly<Record<string, readonly [number, number, number, number]>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

async function main() {
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`LiteLLM price file: HTTP ${res.status}`);
  const rows = pricesFrom(await res.json());
  // A broken or reshaped file must not wipe the table: nothing usable means stop, not an empty list.
  if (rows.length < 5) throw new Error(`Only ${rows.length} Claude prices found — the file's shape may have changed. Nothing written.`);
  const next = render(rows);
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (process.argv.includes("--check")) {
    console.log(next === current ? "Prices are current." : "Prices have changed.");
    process.exit(next === current ? 0 : 1);
  }
  if (next === current) return console.log(`Prices are current (${rows.length} models).`);
  await writeFile(OUT, next);
  console.log(`Wrote ${rows.length} Claude prices.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
